/** `"Luna Cushion Set!"` → `"luna-cushion-set"`. Non-Latin text yields `""`, so callers need a fallback. */
export function slugify(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 160);
}
